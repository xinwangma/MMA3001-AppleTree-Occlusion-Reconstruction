"""Known-camera geometry and evidence-boundary regressions, no real GT claims."""
from dataclasses import replace
import copy
import json
import numpy as np
import pytest
from apple_tree_project.baseline import pixel_graph
from apple_tree_project.reconstruction3d import Calibration, backproject, lift_skeleton, nonmetric_demo


def camera(**overrides):
    base=dict(width=40,height=30,fx=20.,fy=25.,cx=20.,cy=15.,depth_unit_to_m=.001,
              depth_kind='axial_z',invalid_values=(0,65535),registered_to_skeleton=True,rectified=True,
              evidence='Synthetic known camera, scalar millimetres, registered rectified grid')
    base.update(overrides);return Calibration(**base)


def chain():
    mask=np.zeros((30,40),bool);mask[15,5:35]=True
    graph=pixel_graph(mask)
    for n in graph['nodes']:n['inferred']=15<=n['x']<=24
    support=mask.copy();support[15,15:25]=False
    depth=np.full(mask.shape,2000.,float)
    return graph,depth,support


def test_analytic_backprojection_units_and_range():
    p=np.array([[20,15],[30,20],[0,0]])
    xyz,valid=backproject(p,[2000,2000,2000],camera())
    assert valid.all() and np.allclose(xyz,[[0,0,2],[1,.4,2],[-2,-1.2,2]])
    ranged,_=backproject(p,[2000]*3,camera(depth_kind='range'))
    assert np.allclose(np.linalg.norm(ranged,axis=1),2)
    assert np.allclose(ranged[:,0]/ranged[:,2],(p[:,0]-20)/20)


@pytest.mark.parametrize('change',[dict(fx=0),dict(fy=np.nan),dict(depth_unit_to_m=-1),dict(width=0),
    dict(depth_kind='unknown'),dict(registered_to_skeleton=False),dict(rectified=False),dict(evidence='')])
def test_calibration_rejects_unestablished_contract(change):
    with pytest.raises(ValueError):camera(**change)


def test_invalid_depth_is_unsupported_and_grid_not_resized():
    xyz,valid=backproject([[20,15]]*5,[0,65535,np.nan,-1,np.inf],camera())
    assert not valid.any() and np.isnan(xyz).all()
    g,d,s=chain()
    with pytest.raises(ValueError):lift_skeleton(g,d[:2],camera(),s)
    with pytest.raises(ValueError):lift_skeleton(g,np.repeat(d[:,:,None],3,axis=2),camera(),s)
    with pytest.raises(ValueError):backproject([[40,15]],[1],camera())


def test_hidden_foreground_depth_never_measured_and_inputs_preserved():
    g,d,s=chain();before=copy.deepcopy(g);depth_before=d.copy()
    r=lift_skeleton(g,d,camera(),s)
    assert r['status_counts']==dict(measured=20,inferred=0,unsupported=10)
    assert len(r['supported_3d_components'])==2
    assert all(n['xyz_m'] is None for n in r['nodes'] if n['inferred'])
    assert g==before and np.array_equal(d,depth_before)
    r=lift_skeleton(g,d,camera(),s,infer_hidden_depth=True)
    assert r['status_counts']==dict(measured=20,inferred=10,unsupported=0)
    assert len(r['supported_3d_components'])==1
    d[15,15:25]=60000 # unrelated foreground at hidden image coordinates
    other=lift_skeleton(g,d,camera(),s,infer_hidden_depth=True)
    assert r==other
    assert all(n['xyz_m'][2]==pytest.approx(2) for n in r['nodes'])
    json.dumps(r,allow_nan=False)


def test_missing_anchor_or_discontinuity_cannot_be_interpolated():
    g,d,s=chain();d[15,14]=0
    r=lift_skeleton(g,d,camera(),s,infer_hidden_depth=True)
    assert r['status_counts']['inferred']==0
    assert r['hidden_depth_rejections'][0]['reason']=='anchor_depth_unsupported'
    d[15,14]=5000
    r=lift_skeleton(g,d,camera(),s,infer_hidden_depth=True)
    assert r['hidden_depth_rejections'][0]['reason']=='anchor_depth_discontinuity'


def test_nonmetric_real_demo_has_no_physical_coordinates():
    g,d,s=chain();codes=np.full(d.shape,128,dtype='uint8')
    r=nonmetric_demo(g,codes,d.shape)
    assert not r['metric_reconstruction_supported']
    assert all(n['xyz_m'] is None and n['status_3d']=='unsupported' for n in r['nodes'])
    assert all(n['stored_code'] is None and n['display_uvw'][2]==0 for n in r['nodes'] if n['inferred'])
    assert all(e['length_m'] is None for e in r['edges'])


def test_invalid_graph_and_empty_graph():
    g,d,s=chain();bad=copy.deepcopy(g);bad['nodes'][0]['inferred']='false'
    with pytest.raises(ValueError):lift_skeleton(bad,d,camera(),s)
    bad=copy.deepcopy(g);bad['edges'].append(bad['edges'][0])
    with pytest.raises(ValueError):lift_skeleton(bad,d,camera(),s)
    empty=pixel_graph(np.zeros_like(s))
    assert lift_skeleton(empty,d,camera(),s)['status_counts']==dict(measured=0,inferred=0,unsupported=0)


def test_project_backproject_independent_known_3d_tree():
    # Independent 3D Y coordinates projected analytically, not generated by lifting.
    xyz=np.array([[0,.7,3],[0,0,3],[-.7,-.7,3.2],[.7,-.7,2.8]])
    c=camera(depth_unit_to_m=1.)
    pixels=np.c_[c.fx*xyz[:,0]/xyz[:,2]+c.cx,c.fy*xyz[:,1]/xyz[:,2]+c.cy]
    reconstructed,valid=backproject(pixels,xyz[:,2],c)
    assert valid.all() and np.allclose(reconstructed,xyz,atol=1e-12)


def test_branch_support_and_inferred_fork_are_not_filled():
    g,d,s=chain();s[:]=False
    r=lift_skeleton(g,d,camera(),s,infer_hidden_depth=True)
    assert r['status_counts']==dict(measured=0,inferred=0,unsupported=30)
    g,d,s=chain()
    # Attach an extra branch to an inferred interior pixel: no simple-chain
    # depth hypothesis is allowed, even with valid depth at every image pixel.
    i=next(n['id'] for n in g['nodes'] if n['x']==20)
    j=len(g['nodes']);g['nodes'].append(dict(id=j,x=20,y=14,inferred=True,degree=1))
    g['edges'].append(dict(source=i,target=j,inferred=True,length_px=1.))
    r=lift_skeleton(g,d,camera(),s,infer_hidden_depth=True)
    assert r['status_counts']['inferred']==0
    assert r['hidden_depth_rejections'][0]['reason']=='not_a_two_anchor_simple_chain'


def test_explicit_scale_uncertainty_has_expected_geometric_effect():
    p=[[30,20]];raw=[2500]
    nominal,_=backproject(p,raw,camera())
    biased,_=backproject(p,raw,camera(depth_unit_to_m=.0011))
    assert np.allclose(biased,nominal*1.1)


def test_calibrated_cli_outputs_source_preservation_and_guard(tmp_path,monkeypatch):
    import importlib.util
    from pathlib import Path
    from PIL import Image
    from dataclasses import asdict
    path=Path(__file__).parents[1]/'scripts/run_3d_reconstruction.py'
    spec=importlib.util.spec_from_file_location('step5_cli',path)
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
    monkeypatch.setattr(module,'__file__',str(tmp_path/'scripts/run_3d_reconstruction.py'))
    g,d,s=chain()
    gp,dp,cp,sp=[tmp_path/n for n in ('graph.json','depth.png','camera.json','support.png')]
    gp.write_text(json.dumps(g));cp.write_text(json.dumps(asdict(camera())))
    Image.fromarray(d.astype('uint16')).save(dp)
    Image.fromarray(s.astype('uint8')*255).save(sp)
    original={p:p.read_bytes() for p in (gp,dp,cp,sp)}
    out=tmp_path/'results/run'
    counts=module.run(gp,dp,cp,sp,out,True)
    assert counts==dict(measured=20,inferred=10,unsupported=0)
    assert (out/'points.csv').exists()
    assert json.loads((out/'graph3d.json').read_text())['units']=='metres'
    assert all(p.read_bytes()==data for p,data in original.items())
    with pytest.raises(ValueError):module.run(gp,dp,cp,sp,out)
    with pytest.raises(ValueError):module.run(gp,dp,cp,sp,tmp_path/'unsafe')
